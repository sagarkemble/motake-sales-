#!/usr/bin/env bash
set -euo pipefail

# Writes root .env from environment variables (no prompts).
# Used by GitHub Actions and remote CI deploy on the VPS.

# shellcheck disable=SC1091
source "$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)/lib/common.sh"

SYMLINK_TARGETS=(
  "apps/api/.env"
  "apps/web/.env.local"
  "packages/database/.env"
  "packages/services/.env"
  "packages/logger/.env"
)

REQUIRED_VARS=(
  DATABASE_URL
  JWT_SECRET
  SUPABASE_URL
  SUPABASE_SERVICE_ROLE_KEY
  IMAGEKIT_PUBLIC_KEY
  IMAGEKIT_PRIVATE_KEY
  IMAGEKIT_URL_ENDPOINT
  NEXT_PUBLIC_API_URL
  NEXT_PUBLIC_SUPABASE_URL
  NEXT_PUBLIC_SUPABASE_ANON_KEY
  BASE_URL
)

usage() {
  cat <<EOF
Usage: $(basename "$0")

Write root .env from environment variables and create symlinks.

Required environment variables:
  DATABASE_URL, JWT_SECRET, SUPABASE_URL, SUPABASE_SERVICE_ROLE_KEY
  IMAGEKIT_PUBLIC_KEY, IMAGEKIT_PRIVATE_KEY, IMAGEKIT_URL_ENDPOINT
  NEXT_PUBLIC_API_URL, NEXT_PUBLIC_SUPABASE_URL, NEXT_PUBLIC_SUPABASE_ANON_KEY
  BASE_URL

Optional (defaults applied if unset):
  PORT, NODE_ENV, LOGGER_LEVEL, CORS_ALLOWED_ORIGIN, MOTAKE_NOTIFICATION_PORT

Notification service (switched on by NOTIFICATION_INTERNAL_API_KEY; then all are required,
unset skips the notification container):
  NOTIFICATION_INTERNAL_API_KEY, META_PHONE_NUMBER_ID, META_APP_SECRET,
  META_WEBHOOK_VERIFY_TOKEN, INNGEST_EVENT_KEY, INNGEST_SIGNING_KEY, IMAGEKIT_PRIVATE_KEY
  These go to deploy/generated/notification.env (mode 600) with IMAGEKIT_URL_ENDPOINT, not
  the root .env; the root .env only gets NOTIFICATION_URL, NOTIFICATION_INTERNAL_API_KEY and
  META_PHONE_NUMBER_ID (to check a pasted WhatsApp token) for the main API. The WhatsApp access
  token is not an env value: it lives in Supabase Vault (Spec J-0).
EOF
}

while [[ $# -gt 0 ]]; do
  case "$1" in
    -h | --help)
      usage
      exit 0
      ;;
    *)
      echo "Unknown option: $1" >&2
      usage >&2
      exit 1
      ;;
  esac
done

for var in "${REQUIRED_VARS[@]}"; do
  if [[ -z "${!var:-}" ]]; then
    echo "error: required environment variable ${var} is not set" >&2
    exit 1
  fi
done

PORT="${PORT:-8000}"
NODE_ENV="${NODE_ENV:-production}"
LOGGER_LEVEL="${LOGGER_LEVEL:-error}"
CORS_ALLOWED_ORIGIN="${CORS_ALLOWED_ORIGIN:-}"

cat >"$ENV_FILE" <<EOF
# Generated by deploy/ci/write-env.sh — $(date -u +"%Y-%m-%dT%H:%M:%SZ")
# Do not edit manually on production — update GitHub Secrets instead.

PORT=${PORT}
NODE_ENV=${NODE_ENV}
BASE_URL=${BASE_URL}

DATABASE_URL=${DATABASE_URL}

LOGGER_LEVEL=${LOGGER_LEVEL}

JWT_SECRET=${JWT_SECRET}
SUPABASE_URL=${SUPABASE_URL}
SUPABASE_SERVICE_ROLE_KEY=${SUPABASE_SERVICE_ROLE_KEY}
IMAGEKIT_PUBLIC_KEY=${IMAGEKIT_PUBLIC_KEY}
IMAGEKIT_PRIVATE_KEY=${IMAGEKIT_PRIVATE_KEY}
IMAGEKIT_URL_ENDPOINT=${IMAGEKIT_URL_ENDPOINT}

NEXT_PUBLIC_API_URL=${NEXT_PUBLIC_API_URL}
NEXT_PUBLIC_SUPABASE_URL=${NEXT_PUBLIC_SUPABASE_URL}
NEXT_PUBLIC_SUPABASE_ANON_KEY=${NEXT_PUBLIC_SUPABASE_ANON_KEY}
EOF

if [[ -n "$CORS_ALLOWED_ORIGIN" ]]; then
  echo "CORS_ALLOWED_ORIGIN=${CORS_ALLOWED_ORIGIN}" >>"$ENV_FILE"
fi

# The main API's side of the notification boundary (Spec J); the port is confirmed by deploy.sh.
if [[ -n "${NOTIFICATION_INTERNAL_API_KEY:-}" ]]; then
  {
    echo
    echo "NOTIFICATION_URL=http://127.0.0.1:${MOTAKE_NOTIFICATION_PORT:-$DEFAULT_NOTIFICATION_PORT}"
    echo "NOTIFICATION_INTERNAL_API_KEY=${NOTIFICATION_INTERNAL_API_KEY}"
    echo "META_PHONE_NUMBER_ID=${META_PHONE_NUMBER_ID:-}"
  } >>"$ENV_FILE"
fi

echo "write .env"

write_notification_env || true

create_symlink() {
  local target_rel="$1"
  local target="$ROOT_DIR/$target_rel"
  local link_target="../../.env"

  mkdir -p "$(dirname "$target")"

  if [[ -e "$target" || -L "$target" ]]; then
    rm -f "$target"
  fi

  ln -sf "$link_target" "$target"
  echo "link  $target_rel -> $link_target"
}

echo
echo "Creating symlinks..."
for target_rel in "${SYMLINK_TARGETS[@]}"; do
  create_symlink "$target_rel"
done

echo "Done."
