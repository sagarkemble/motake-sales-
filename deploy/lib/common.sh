#!/usr/bin/env bash
# Shared deployment helpers — sourced by deploy/vps/* and deploy/ci/*

DEPLOY_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
ROOT_DIR="$(cd "$DEPLOY_DIR/.." && pwd)"
ENV_FILE="$ROOT_DIR/.env"
GENERATED_DIR="$DEPLOY_DIR/generated"
PM2_DIR="$DEPLOY_DIR/pm2"
CADDY_DIR="$DEPLOY_DIR/caddy"

DEFAULT_WEB_PORT=3000
DEFAULT_API_PORT=8000
DEFAULT_NOTIFICATION_PORT=8100
PM2_API_NAME="motake-api"
PM2_WEB_NAME="motake-web"

# Notification service (ADR-0001): one Docker container with the app and self-hosted Inngest.
NOTIFICATION_CONTAINER_NAME="motake-notification"
NOTIFICATION_IMAGE="motake-notification:latest"
NOTIFICATION_VOLUME="motake-inngest-data"
NOTIFICATION_DOCKERFILE="apps/notification/Dockerfile"

RUNTIME_ENV="$GENERATED_DIR/runtime.env"
ECOSYSTEM_FILE="$GENERATED_DIR/ecosystem.config.cjs"
MOTAKE_FRAGMENT="$GENERATED_DIR/motake.caddy"
LOCAL_CADDYFILE="$GENERATED_DIR/Caddyfile"
# Only the notification container's secrets; kept out of the root .env the API process loads.
NOTIFICATION_ENV_FILE="$GENERATED_DIR/notification.env"

# The notification container's own secrets: all or none, switched on by
# NOTIFICATION_INTERNAL_API_KEY. Meta, Inngest and the R2 read key are separate secrets.
NOTIFICATION_SECRET_VARS=(
  NOTIFICATION_INTERNAL_API_KEY
  META_PHONE_NUMBER_ID
  META_APP_SECRET
  META_WEBHOOK_VERIFY_TOKEN
  INNGEST_EVENT_KEY
  INNGEST_SIGNING_KEY
  NOTIFICATION_R2_ACCOUNT_ID
  NOTIFICATION_R2_ACCESS_KEY_ID
  NOTIFICATION_R2_SECRET_ACCESS_KEY
)

# Root values the container also gets. Always set for the API (Spec L), so they never decide
# whether the notification service is configured.
NOTIFICATION_SHARED_VARS=(
  R2_DOCUMENTS_BUCKET_NAME
)

trim_whitespace() {
  local input="$1"
  input="${input#"${input%%[![:space:]]*}"}"
  input="${input%"${input##*[![:space:]]}"}"
  printf '%s' "$input"
}

normalize_pasted_value() {
  local key="$1"
  local value="$2"

  value="${value//$'\r'/}"

  if [[ "$value" == *$'\n'* ]]; then
    echo "  note: multi-line paste detected; using the first line only." >&2
    value="${value%%$'\n'*}"
  fi

  if [[ "$value" =~ ^${key}=(.*)$ ]]; then
    value="${BASH_REMATCH[1]}"
  elif [[ "$value" =~ ^[A-Za-z_][A-Za-z0-9_]*=(.*)$ ]]; then
    echo "  note: extracted value from pasted KEY=value line." >&2
    value="${BASH_REMATCH[1]}"
  fi

  trim_whitespace "$value"
}

drain_extra_tty_input() {
  local extra=""

  while true; do
    if ! IFS= read -r -t 0.01 extra <&3; then
      break
    fi

    extra="$(trim_whitespace "${extra//$'\r'/}")"
    if [[ -n "$extra" ]]; then
      echo "  ! ignored extra pasted input (paste one value per prompt): $extra" >&2
    fi
  done
}

prompt_for_value() {
  local key="$1"
  local default="$2"
  local value=""
  local prompt="  $key"

  if [[ -n "$default" ]]; then
    prompt+=" [$default]"
  fi
  prompt+=": "

  if ! IFS= read -e -r -p "$prompt" value <&3; then
    value=""
  fi

  value="$(normalize_pasted_value "$key" "$value")"
  drain_extra_tty_input

  if [[ -z "$value" ]]; then
    value="$default"
  fi

  REPLY="$value"
}

validate_domain() {
  local domain="$1"

  if [[ -z "$domain" ]]; then
    echo "error: domain cannot be empty" >&2
    return 1
  fi

  if [[ ! "$domain" =~ ^[a-zA-Z0-9]([a-zA-Z0-9-]*[a-zA-Z0-9])?(\.[a-zA-Z0-9]([a-zA-Z0-9-]*[a-zA-Z0-9])?)*$ ]]; then
    echo "error: invalid domain: $domain" >&2
    return 1
  fi
}

validate_port() {
  local port="$1"

  if [[ ! "$port" =~ ^[0-9]+$ ]] || (( port < 1 || port > 65535 )); then
    echo "error: invalid port: $port" >&2
    return 1
  fi
}

is_port_in_use() {
  local port="$1"

  if command -v ss >/dev/null 2>&1; then
    ss -tulnH "sport = :${port}" 2>/dev/null | grep -q .
    return $?
  fi

  if command -v lsof >/dev/null 2>&1; then
    lsof -iTCP:"${port}" -sTCP:LISTEN -t >/dev/null 2>&1
    return $?
  fi

  (echo >/dev/tcp/127.0.0.1/"${port}") >/dev/null 2>&1
}

find_available_port() {
  local port="$1"

  while is_port_in_use "$port"; do
    echo "  port ${port} is in use, trying next..." >&2
    port=$((port + 1))
  done

  printf '%s' "$port"
}

update_env_key() {
  local key="$1"
  local value="$2"

  if [[ ! -f "$ENV_FILE" ]]; then
    echo "error: $ENV_FILE not found" >&2
    return 1
  fi

  if grep -q "^${key}=" "$ENV_FILE"; then
    sed -i "s|^${key}=.*|${key}=${value}|" "$ENV_FILE"
  else
    echo "${key}=${value}" >>"$ENV_FILE"
  fi

  echo "  update .env  ${key}=${value}"
}

write_runtime_env() {
  local web_port="$1"
  local api_port="$2"
  local notification_port="${3:-$DEFAULT_NOTIFICATION_PORT}"

  mkdir -p "$GENERATED_DIR"

  cat >"$RUNTIME_ENV" <<EOF
# Generated by deploy scripts — $(date -u +"%Y-%m-%dT%H:%M:%SZ")
MOTAKE_WEB_PORT=${web_port}
MOTAKE_API_PORT=${api_port}
MOTAKE_NOTIFICATION_PORT=${notification_port}
EOF
}

write_ecosystem_file() {
  mkdir -p "$GENERATED_DIR"

  cat >"$ECOSYSTEM_FILE" <<EOF
/** Generated by deploy scripts — $(date -u +"%Y-%m-%dT%H:%M:%SZ") */
module.exports = {
  apps: [
    {
      name: "${PM2_API_NAME}",
      script: "${PM2_DIR}/start-api.sh",
      interpreter: "bash",
      cwd: "${ROOT_DIR}",
      autorestart: true,
      max_restarts: 10,
      watch: false,
    },
    {
      name: "${PM2_WEB_NAME}",
      script: "${PM2_DIR}/start-web.sh",
      interpreter: "bash",
      cwd: "${ROOT_DIR}",
      autorestart: true,
      max_restarts: 10,
      watch: false,
    },
  ],
};
EOF
}

require_command() {
  local cmd="$1"
  local hint="$2"

  if ! command -v "$cmd" >/dev/null 2>&1; then
    echo "error: '${cmd}' is not installed." >&2
    echo "$hint" >&2
    exit 1
  fi
}

stop_pm2_apps() {
  pm2 delete "$PM2_API_NAME" >/dev/null 2>&1 || true
  pm2 delete "$PM2_WEB_NAME" >/dev/null 2>&1 || true
}

ensure_deploy_dirs() {
  mkdir -p "$GENERATED_DIR"
  chmod +x "$PM2_DIR/start-api.sh" "$PM2_DIR/start-web.sh"
}

assign_ports() {
  local web_port="$DEFAULT_WEB_PORT"
  local api_port="$DEFAULT_API_PORT"
  local notification_port="$DEFAULT_NOTIFICATION_PORT"

  if [[ -f "$RUNTIME_ENV" ]]; then
    # shellcheck disable=SC1090
    source "$RUNTIME_ENV"
    web_port="${MOTAKE_WEB_PORT:-$DEFAULT_WEB_PORT}"
    api_port="${MOTAKE_API_PORT:-$DEFAULT_API_PORT}"
    notification_port="${MOTAKE_NOTIFICATION_PORT:-$DEFAULT_NOTIFICATION_PORT}"
  fi

  if [[ -f "$ENV_FILE" ]]; then
    api_port="$(grep "^PORT=" "$ENV_FILE" | head -1 | cut -d= -f2- || echo "$DEFAULT_API_PORT")"
    api_port="${api_port:-$DEFAULT_API_PORT}"
  fi

  if [[ "${MOTAKE_WEB_PORT:-}" != "" ]]; then
    web_port="$MOTAKE_WEB_PORT"
  fi
  if [[ "${MOTAKE_API_PORT:-}" != "" ]]; then
    api_port="$MOTAKE_API_PORT"
  fi

  stop_pm2_apps

  if is_port_in_use "$web_port"; then
    web_port="$(find_available_port "$web_port")"
  fi

  if is_port_in_use "$api_port"; then
    api_port="$(find_available_port "$api_port")"
  fi

  if [[ "$web_port" == "$api_port" ]]; then
    api_port="$(find_available_port "$((api_port + 1))")"
  fi

  # The running notification container holds its own port until it is replaced; keep that port.
  if is_port_in_use "$notification_port" && ! notification_container_owns_port "$notification_port"; then
    notification_port="$(find_available_port "$notification_port")"
  fi
  if [[ "$notification_port" == "$web_port" || "$notification_port" == "$api_port" ]]; then
    notification_port="$(find_available_port "$((notification_port + 1))")"
  fi

  write_runtime_env "$web_port" "$api_port" "$notification_port"

  DEPLOY_WEB_PORT="$web_port"
  DEPLOY_API_PORT="$api_port"
  DEPLOY_NOTIFICATION_PORT="$notification_port"
}

notification_container_owns_port() {
  local port="$1"

  command -v docker >/dev/null 2>&1 || return 1
  docker_cmd port "$NOTIFICATION_CONTAINER_NAME" 2>/dev/null | grep -q ":${port}$"
}

# Runs docker as the deploy user. ensure-production.sh adds the user to the docker group, which
# a running SSH session only picks up on the next login, so until then go through `sg docker`.
DOCKER_VIA_SG=""
docker_cmd() {
  if [[ -z "$DOCKER_VIA_SG" ]]; then
    if docker info >/dev/null 2>&1; then
      DOCKER_VIA_SG=no
    elif command -v sg >/dev/null 2>&1 && sg docker -c "docker info" >/dev/null 2>&1; then
      DOCKER_VIA_SG=yes
    else
      DOCKER_VIA_SG=no
    fi
  fi

  if [[ "$DOCKER_VIA_SG" == yes ]]; then
    sg docker -c "$(printf '%q ' docker "$@")"
  else
    docker "$@"
  fi
}

# Value of KEY from the environment, else from the root .env.
read_deploy_value() {
  local key="$1"

  if [[ -n "${!key:-}" ]]; then
    printf '%s' "${!key}"
    return 0
  fi

  if [[ -f "$ENV_FILE" ]]; then
    grep "^${key}=" "$ENV_FILE" | head -1 | cut -d= -f2- || true
  fi
}

# The notification service is switched on by NOTIFICATION_INTERNAL_API_KEY alone.
notification_configured() {
  [[ -n "$(read_deploy_value NOTIFICATION_INTERNAL_API_KEY)" ]]
}

# Writes deploy/generated/notification.env (mode 600) for the container. Returns 1 and writes
# nothing while NOTIFICATION_INTERNAL_API_KEY is unset; fails when it is set and any other
# notification secret or shared value is missing.
write_notification_env() {
  local missing=()
  local var

  if ! notification_configured; then
    rm -f "$NOTIFICATION_ENV_FILE"
    echo "  warn: NOTIFICATION_INTERNAL_API_KEY not set — the notification container is skipped" >&2
    return 1
  fi

  for var in "${NOTIFICATION_SECRET_VARS[@]}" "${NOTIFICATION_SHARED_VARS[@]}"; do
    if [[ -z "$(read_deploy_value "$var")" ]]; then
      missing+=("$var")
    fi
  done

  if [[ ${#missing[@]} -gt 0 ]]; then
    echo "error: notification secrets missing: ${missing[*]}" >&2
    exit 1
  fi

  mkdir -p "$GENERATED_DIR"
  (
    umask 077
    {
      echo "# Generated by deploy scripts — $(date -u +"%Y-%m-%dT%H:%M:%SZ")"
      echo "NODE_ENV=production"
      echo "LOGGER_LEVEL=$(read_deploy_value LOGGER_LEVEL)"
      echo "DATABASE_URL=$(read_deploy_value DATABASE_URL)"
      for var in "${NOTIFICATION_SECRET_VARS[@]}" "${NOTIFICATION_SHARED_VARS[@]}"; do
        echo "${var}=$(read_deploy_value "$var")"
      done
    } >"$NOTIFICATION_ENV_FILE"
  )
  chmod 600 "$NOTIFICATION_ENV_FILE"
  echo "write ${NOTIFICATION_ENV_FILE}"
}

# Builds the image from the repo, replaces the container and waits for /health. Inngest state
# stays on the named volume, so queued sends survive the swap. Returns 1 on any failure (callers
# run it after api/web are up and turn a failure into a loud warning), so every step checks.
deploy_notification_container() {
  local port="${DEPLOY_NOTIFICATION_PORT:-$DEFAULT_NOTIFICATION_PORT}"

  if [[ ! -f "$NOTIFICATION_ENV_FILE" ]]; then
    echo "skip  notification container (no ${NOTIFICATION_ENV_FILE})"
    return 0
  fi

  if ! command -v docker >/dev/null 2>&1; then
    echo "error: docker not found — deploy/ci/ensure-production.sh installs it once" \
      "NOTIFICATION_INTERNAL_API_KEY is set" >&2
    return 1
  fi

  echo
  echo "Building notification image..."
  docker_cmd build -f "$ROOT_DIR/$NOTIFICATION_DOCKERFILE" -t "$NOTIFICATION_IMAGE" "$ROOT_DIR" ||
    return 1

  echo "Replacing notification container..."
  # Up to 30 s for an in-flight send to finish before the old container is killed.
  docker_cmd stop -t 30 "$NOTIFICATION_CONTAINER_NAME" >/dev/null 2>&1 || true
  docker_cmd rm -f "$NOTIFICATION_CONTAINER_NAME" >/dev/null 2>&1 || true
  docker_cmd volume create "$NOTIFICATION_VOLUME" >/dev/null || return 1
  # Published on localhost only; Caddy forwards just the webhook path. The Inngest dashboard
  # port is not published.
  docker_cmd run -d \
    --name "$NOTIFICATION_CONTAINER_NAME" \
    --restart unless-stopped \
    --init \
    --env-file "$NOTIFICATION_ENV_FILE" \
    -e HOST=0.0.0.0 \
    -e PORT="$port" \
    -p "127.0.0.1:${port}:${port}" \
    -v "${NOTIFICATION_VOLUME}:/var/lib/inngest" \
    "$NOTIFICATION_IMAGE" >/dev/null || return 1

  health_check_notification || return 1

  # The previous image is now dangling; drop it so builds do not fill the disk.
  docker_cmd image prune -f >/dev/null || true
}

health_check_notification() {
  local port="${DEPLOY_NOTIFICATION_PORT:-$DEFAULT_NOTIFICATION_PORT}"
  local attempt

  for attempt in $(seq 1 30); do
    if curl -sf "http://127.0.0.1:${port}/health" >/dev/null; then
      echo "  notification  OK  http://127.0.0.1:${port}/health"
      return 0
    fi
    sleep 2
  done

  echo "  notification  FAIL  http://127.0.0.1:${port}/health" >&2
  curl -s "http://127.0.0.1:${port}/health" >&2 || true
  docker_cmd logs --tail 50 "$NOTIFICATION_CONTAINER_NAME" >&2 || true
  return 1
}

verify_build_artifacts() {
  if [[ ! -f "$ROOT_DIR/apps/api/dist/index.js" ]]; then
    echo "error: API build missing — run pnpm build first" >&2
    exit 1
  fi

  if [[ ! -d "$ROOT_DIR/apps/web/.next" ]]; then
    echo "error: Web build missing — run pnpm build first" >&2
    exit 1
  fi
}

start_pm2_apps() {
  write_ecosystem_file

  echo
  echo "Starting PM2 processes..."
  pm2 start "$ECOSYSTEM_FILE" --update-env
  pm2 save

  if command -v systemctl >/dev/null 2>&1; then
    pm2 startup systemd -u "$USER" --hp "$HOME" >/dev/null 2>&1 || true
  fi

  echo
  pm2 status
}

run_caddy_setup() {
  local caddy_script="$DEPLOY_DIR/vps/caddy-setup.sh"

  if [[ ! -x "$caddy_script" ]]; then
    echo "error: caddy-setup.sh not found or not executable" >&2
    exit 1
  fi

  MOTAKE_ROUTING_MODE="$DEPLOY_ROUTING_MODE" \
    MOTAKE_FRONTEND_DOMAIN="$DEPLOY_FRONTEND_DOMAIN" \
    MOTAKE_API_DOMAIN="$DEPLOY_API_DOMAIN" \
    MOTAKE_FRONTEND_PORT="$DEPLOY_WEB_PORT" \
    MOTAKE_API_PORT="$DEPLOY_API_PORT" \
    MOTAKE_NOTIFICATION_PORT="${DEPLOY_NOTIFICATION_PORT:-$DEFAULT_NOTIFICATION_PORT}" \
    MOTAKE_INSTALL_TARGET="${MOTAKE_INSTALL_TARGET:-system}" \
    MOTAKE_UPDATE_ENV="no" \
    "$caddy_script" --non-interactive --force
}

health_check_local() {
  local api_port="${DEPLOY_API_PORT:-8000}"
  local web_port="${DEPLOY_WEB_PORT:-3000}"

  echo
  echo "Health checks (localhost)..."

  if curl -sf "http://127.0.0.1:${api_port}/health" >/dev/null; then
    echo "  api  OK  http://127.0.0.1:${api_port}/health"
  else
    echo "  api  FAIL  http://127.0.0.1:${api_port}/health" >&2
    return 1
  fi

  if curl -sfI "http://127.0.0.1:${web_port}" >/dev/null; then
    echo "  web  OK  http://127.0.0.1:${web_port}"
  else
    echo "  web  FAIL  http://127.0.0.1:${web_port}" >&2
    return 1
  fi
}
