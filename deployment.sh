#!/usr/bin/env bash
set -euo pipefail

ROOT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
ENV_FILE="$ROOT_DIR/.env"
DEPLOY_DIR="$ROOT_DIR/deploy"
RUNTIME_ENV="$DEPLOY_DIR/runtime.env"
ECOSYSTEM_FILE="$DEPLOY_DIR/ecosystem.config.cjs"

DEFAULT_WEB_PORT=3001
DEFAULT_API_PORT=8001

PM2_API_NAME="motake-api"
PM2_WEB_NAME="motake-web"

SKIP_BUILD=false
SKIP_CADDY=false
FORCE=false

usage() {
  cat <<EOF
Usage: $(basename "$0") [--force] [--skip-build] [--skip-caddy]

Deploy Motake to a VPS with PM2 + Caddy.

Steps:
  1/3  Check ports (3001 web, 8001 api) and assign free ports if busy
  2/3  Configure domains, build production apps, start/restart PM2 processes
  3/3  Install Caddy reverse-proxy via ./caddy-setup.sh (extends existing config)

Processes managed by PM2:
  motake-api   Express API + tRPC + OpenAPI (bundled in one server)
  motake-web   Next.js frontend

Prerequisites:
  ./env-setup.sh          — root .env configured
  pnpm install            — dependencies installed
  pm2, caddy              — installed on the server

Examples:
  ./deployment.sh
  ./deployment.sh --force
  ./deployment.sh --skip-caddy
EOF
}

while [[ $# -gt 0 ]]; do
  case "$1" in
    --force)
      FORCE=true
      shift
      ;;
    --skip-build)
      SKIP_BUILD=true
      shift
      ;;
    --skip-caddy)
      SKIP_CADDY=true
      shift
      ;;
    -h | --help)
      usage
      exit 0
      ;;
    *)
      echo "Unknown option: $1" >&2
      usage >&2
      exit 1
      ;;
  esac
done

trim_whitespace() {
  local input="$1"
  input="${input#"${input%%[![:space:]]*}"}"
  input="${input%"${input##*[![:space:]]}"}"
  printf '%s' "$input"
}

normalize_pasted_value() {
  local key="$1"
  local value="$2"

  value="${value//$'\r'/}"

  if [[ "$value" == *$'\n'* ]]; then
    echo "  note: multi-line paste detected; using the first line only." >&2
    value="${value%%$'\n'*}"
  fi

  if [[ "$value" =~ ^${key}=(.*)$ ]]; then
    value="${BASH_REMATCH[1]}"
  elif [[ "$value" =~ ^[A-Za-z_][A-Za-z0-9_]*=(.*)$ ]]; then
    echo "  note: extracted value from pasted KEY=value line." >&2
    value="${BASH_REMATCH[1]}"
  fi

  trim_whitespace "$value"
}

drain_extra_tty_input() {
  local extra=""

  while true; do
    if ! IFS= read -r -t 0.01 extra <&3; then
      break
    fi

    extra="$(trim_whitespace "${extra//$'\r'/}")"
    if [[ -n "$extra" ]]; then
      echo "  ! ignored extra pasted input (paste one value per prompt): $extra" >&2
    fi
  done
}

prompt_for_value() {
  local key="$1"
  local default="$2"
  local value=""
  local prompt="  $key"

  if [[ -n "$default" ]]; then
    prompt+=" [$default]"
  fi
  prompt+=": "

  if ! IFS= read -e -r -p "$prompt" value <&3; then
    value=""
  fi

  value="$(normalize_pasted_value "$key" "$value")"
  drain_extra_tty_input

  if [[ -z "$value" ]]; then
    value="$default"
  fi

  REPLY="$value"
}

validate_domain() {
  local domain="$1"

  if [[ -z "$domain" ]]; then
    echo "error: domain cannot be empty" >&2
    return 1
  fi

  if [[ ! "$domain" =~ ^[a-zA-Z0-9]([a-zA-Z0-9-]*[a-zA-Z0-9])?(\.[a-zA-Z0-9]([a-zA-Z0-9-]*[a-zA-Z0-9])?)*$ ]]; then
    echo "error: invalid domain: $domain" >&2
    return 1
  fi
}

is_port_in_use() {
  local port="$1"

  if command -v ss >/dev/null 2>&1; then
    ss -tulnH "sport = :${port}" 2>/dev/null | grep -q .
    return $?
  fi

  if command -v lsof >/dev/null 2>&1; then
    lsof -iTCP:"${port}" -sTCP:LISTEN -t >/dev/null 2>&1
    return $?
  fi

  (echo >/dev/tcp/127.0.0.1/"${port}") >/dev/null 2>&1
}

find_available_port() {
  local port="$1"

  while is_port_in_use "$port"; do
    echo "  port ${port} is in use, trying next..." >&2
    port=$((port + 1))
  done

  printf '%s' "$port"
}

update_env_key() {
  local key="$1"
  local value="$2"

  if grep -q "^${key}=" "$ENV_FILE"; then
    sed -i "s|^${key}=.*|${key}=${value}|" "$ENV_FILE"
  else
    echo "${key}=${value}" >>"$ENV_FILE"
  fi

  echo "  update .env  ${key}=${value}"
}

write_runtime_env() {
  local web_port="$1"
  local api_port="$2"

  cat >"$RUNTIME_ENV" <<EOF
# Generated by deployment.sh — $(date -u +"%Y-%m-%dT%H:%M:%SZ")
MOTAKE_WEB_PORT=${web_port}
MOTAKE_API_PORT=${api_port}
EOF
}

write_ecosystem_file() {
  cat >"$ECOSYSTEM_FILE" <<EOF
/** Generated by deployment.sh — $(date -u +"%Y-%m-%dT%H:%M:%SZ") */
module.exports = {
  apps: [
    {
      name: "${PM2_API_NAME}",
      script: "${DEPLOY_DIR}/pm2-start-api.sh",
      interpreter: "bash",
      cwd: "${ROOT_DIR}",
      autorestart: true,
      max_restarts: 10,
      watch: false,
    },
    {
      name: "${PM2_WEB_NAME}",
      script: "${DEPLOY_DIR}/pm2-start-web.sh",
      interpreter: "bash",
      cwd: "${ROOT_DIR}",
      autorestart: true,
      max_restarts: 10,
      watch: false,
    },
  ],
};
EOF
}

require_command() {
  local cmd="$1"
  local hint="$2"

  if ! command -v "$cmd" >/dev/null 2>&1; then
    echo "error: '${cmd}' is not installed." >&2
    echo "$hint" >&2
    exit 1
  fi
}

stop_pm2_apps() {
  pm2 delete "$PM2_API_NAME" >/dev/null 2>&1 || true
  pm2 delete "$PM2_WEB_NAME" >/dev/null 2>&1 || true
}

step_ports() {
  local web_port="$DEFAULT_WEB_PORT"
  local api_port="$DEFAULT_API_PORT"

  echo
  echo "Step 1/3 — Port assignment"
  echo "────────────────────────"

  if [[ -f "$RUNTIME_ENV" ]]; then
    # shellcheck disable=SC1090
    source "$RUNTIME_ENV"
    web_port="${MOTAKE_WEB_PORT:-$DEFAULT_WEB_PORT}"
    api_port="${MOTAKE_API_PORT:-$DEFAULT_API_PORT}"
  fi

  if [[ -f "$ENV_FILE" ]]; then
    api_port="$(grep "^PORT=" "$ENV_FILE" | head -1 | cut -d= -f2- || echo "$DEFAULT_API_PORT")"
    api_port="${api_port:-$DEFAULT_API_PORT}"
  fi

  stop_pm2_apps

  if is_port_in_use "$web_port"; then
    web_port="$(find_available_port "$web_port")"
  fi

  if is_port_in_use "$api_port"; then
    api_port="$(find_available_port "$api_port")"
  fi

  if [[ "$web_port" == "$api_port" ]]; then
    api_port="$(find_available_port "$((api_port + 1))")"
  fi

  write_runtime_env "$web_port" "$api_port"

  if [[ -f "$ENV_FILE" ]]; then
    update_env_key "PORT" "$api_port"
    update_env_key "BASE_URL" "http://localhost:${api_port}"
  fi

  echo "  web port: ${web_port}"
  echo "  api port: ${api_port}"
  echo "  note: tRPC runs inside motake-api (no separate process)"

  DEPLOY_WEB_PORT="$web_port"
  DEPLOY_API_PORT="$api_port"
}

step_domains_and_build() {
  local routing_mode=""
  local frontend_domain=""
  local api_domain=""
  local base_url=""
  local api_url=""

  echo
  echo "Step 2/3 — Domains, build, and PM2"
  echo "──────────────────────────────────"
  echo "  Paste one value at a time with Ctrl+Shift+V, then press Enter."
  echo

  echo "Routing mode:"
  echo "  1) Separate domains — e.g. app.example.com + api.example.com (recommended)"
  echo "  2) Single domain     — e.g. example.com with /trpc, /api proxied to backend"
  echo
  prompt_for_value "routing_mode" "1"

  case "$REPLY" in
    1 | separate | split)
      routing_mode="separate"
      ;;
    2 | single | path)
      routing_mode="single"
      ;;
    *)
      echo "error: choose 1 or 2" >&2
      exit 1
      ;;
  esac

  echo
  if [[ "$routing_mode" == "separate" ]]; then
    prompt_for_value "frontend_domain" "app.example.com"
    frontend_domain="$REPLY"
    validate_domain "$frontend_domain"

    prompt_for_value "api_domain" "api.example.com"
    api_domain="$REPLY"
    validate_domain "$api_domain"

    base_url="https://${api_domain}"
    api_url="https://${api_domain}/trpc"
  else
    prompt_for_value "domain" "example.com"
    frontend_domain="$REPLY"
    validate_domain "$frontend_domain"
    api_domain="$frontend_domain"
    base_url="https://${frontend_domain}"
    api_url="https://${frontend_domain}/trpc"
  fi

  if [[ -f "$ENV_FILE" ]]; then
    update_env_key "BASE_URL" "$base_url"
    update_env_key "NEXT_PUBLIC_API_URL" "$api_url"
    update_env_key "NODE_ENV" "production"
  else
    echo "error: ${ENV_FILE} not found — run ./env-setup.sh first" >&2
    exit 1
  fi

  DEPLOY_ROUTING_MODE="$routing_mode"
  DEPLOY_FRONTEND_DOMAIN="$frontend_domain"
  DEPLOY_API_DOMAIN="$api_domain"

  if [[ "$SKIP_BUILD" != true ]]; then
    echo
    echo "Installing dependencies..."
    (cd "$ROOT_DIR" && pnpm install --frozen-lockfile 2>/dev/null || pnpm install)

    echo "Running database migrations..."
    (cd "$ROOT_DIR" && pnpm db:migrate) || echo "  warn: db:migrate failed or skipped — check DATABASE_URL"

    echo "Building production apps..."
    (cd "$ROOT_DIR" && pnpm build)
  else
    echo "skip  build (--skip-build)"
  fi

  if [[ ! -f "$ROOT_DIR/apps/api/dist/index.js" ]]; then
    echo "error: API build missing — run pnpm build first" >&2
    exit 1
  fi

  if [[ ! -d "$ROOT_DIR/apps/web/.next" ]]; then
    echo "error: Web build missing — run pnpm build first" >&2
    exit 1
  fi

  write_ecosystem_file

  echo
  echo "Starting PM2 processes..."
  pm2 start "$ECOSYSTEM_FILE" --update-env
  pm2 save

  if command -v systemctl >/dev/null 2>&1; then
    pm2 startup systemd -u "$USER" --hp "$HOME" >/dev/null 2>&1 || true
  fi

  echo
  pm2 status
}

step_caddy() {
  echo
  echo "Step 3/3 — Caddy reverse proxy"
  echo "─────────────────────────────"

  if [[ "$SKIP_CADDY" == true ]]; then
    echo "skip  caddy (--skip-caddy)"
    return 0
  fi

  if [[ ! -x "$ROOT_DIR/caddy-setup.sh" ]]; then
    echo "error: caddy-setup.sh not found or not executable" >&2
    exit 1
  fi

  MOTAKE_ROUTING_MODE="$DEPLOY_ROUTING_MODE" \
    MOTAKE_FRONTEND_DOMAIN="$DEPLOY_FRONTEND_DOMAIN" \
    MOTAKE_API_DOMAIN="$DEPLOY_API_DOMAIN" \
    MOTAKE_FRONTEND_PORT="$DEPLOY_WEB_PORT" \
    MOTAKE_API_PORT="$DEPLOY_API_PORT" \
    MOTAKE_INSTALL_TARGET="system" \
    MOTAKE_UPDATE_ENV="no" \
    "$ROOT_DIR/caddy-setup.sh" --non-interactive --force
}

main() {
  if [[ ! -e /dev/tty ]]; then
    echo "error: interactive terminal required (run directly in a terminal)" >&2
    exit 1
  fi

  if [[ ! -f "$ENV_FILE" ]]; then
    echo "error: ${ENV_FILE} not found — run ./env-setup.sh first" >&2
    exit 1
  fi

  require_command "pnpm" "Install Node.js 22+ and pnpm: https://pnpm.io/installation"
  require_command "pm2" "Install PM2 globally: npm install -g pm2"
  require_command "node" "Install Node.js 22+: https://nodejs.org"

  mkdir -p "$DEPLOY_DIR"
  chmod +x "$DEPLOY_DIR/pm2-start-api.sh" "$DEPLOY_DIR/pm2-start-web.sh"

  exec 3</dev/tty

  echo "Motake deployment"
  echo "  root: ${ROOT_DIR}"

  step_ports
  step_domains_and_build
  exec 3<&-
  step_caddy

  echo
  echo "Deployment complete."
  echo "  Frontend: https://${DEPLOY_FRONTEND_DOMAIN}"
  if [[ "$DEPLOY_ROUTING_MODE" == "separate" ]]; then
    echo "  API:      https://${DEPLOY_API_DOMAIN}/trpc"
  else
    echo "  API:      https://${DEPLOY_FRONTEND_DOMAIN}/trpc"
  fi
  echo "  Web port: ${DEPLOY_WEB_PORT}  |  API port: ${DEPLOY_API_PORT}"
  echo
  echo "PM2 commands:"
  echo "  pm2 status"
  echo "  pm2 logs"
  echo "  pm2 restart ${PM2_API_NAME} ${PM2_WEB_NAME}"
}

main "$@"
